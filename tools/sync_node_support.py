"""Regenerate everything derived from schema/node-support.json.

schema/node-support.json is the single source of truth for node status (SPEC §7).
This script rewrites:

- the node table in README.md (between the node-table markers);
- exporter/node_support.py (Blender node type -> status, used to report unsupported nodes).

Usage:
    python3 tools/sync_node_support.py          # rewrite files
    python3 tools/sync_node_support.py --check  # exit 1 if anything is out of date (CI)
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "schema" / "node-support.json"
README = ROOT / "README.md"
PY_OUT = ROOT / "exporter" / "node_support.py"

START = "<!-- node-table:start (generated by tools/sync_node_support.py from schema/node-support.json) -->"
END = "<!-- node-table:end -->"

STATUS_LABEL = {
    "supported": "✅ Supported",
    "partial": "🟡 Partial",
    "planned": "🚧 Not yet",
    "baked": "🧊 Baked",
    "not_planned": "❌ Not planned",
}


def load():
    entries = json.loads(SOURCE.read_text(encoding="utf-8"))
    seen = set()
    for e in entries:
        if e["status"] not in STATUS_LABEL:
            raise SystemExit(f"{e['name']}: unknown status {e['status']!r}")
        for t in e["types"]:
            if t in seen:
                raise SystemExit(f"node type {t} listed twice")
            seen.add(t)
    return entries


def render_table(entries):
    lines = [
        START,
        "",
        "✅ Supported · 🟡 Partial · 🚧 Not yet · 🧊 Baked · ❌ Not planned",
        "",
        "This table lists every shader node in Blender 4.2 LTS and 5.2 LTS. "
        "Nodes that exist in only one of those versions are marked in Notes.",
    ]
    sections = []
    for e in entries:
        if e["section"] not in sections:
            sections.append(e["section"])
    for section in sections:
        lines += ["", f"### {section}", "", "| Node | Category | Status | Phase | Notes |", "|---|---|---|---|---|"]
        for e in entries:
            if e["section"] != section:
                continue
            phase = "—" if e["phase"] is None else str(e["phase"])
            notes = f" {e['notes']} " if e.get("notes") else " "
            lines.append(f"| {e['name']} | {e['category']} | {STATUS_LABEL[e['status']]} | {phase} |{notes}|")
    lines += ["", END]
    return "\n".join(lines)


def render_readme(entries):
    text = README.read_text(encoding="utf-8")
    try:
        head, rest = text.split(START, 1)
        _, tail = rest.split(END, 1)
    except ValueError:
        raise SystemExit("README.md is missing the node-table markers") from None
    return head + render_table(entries) + tail


def render_python(entries):
    lines = [
        '"""Node support status.',
        "",
        "GENERATED by tools/sync_node_support.py from schema/node-support.json. Do not edit.",
        '"""',
        "",
        "# Statuses that the three.js runtime evaluates live.",
        'LIVE = frozenset({"supported", "partial"})',
        "",
        "STATUS = {",
    ]
    for t, status in sorted((t, e["status"]) for e in entries for t in e["types"]):
        lines.append(f'    "{t}": "{status}",')
    lines += ["}", "", "NAME = {"]
    for t, name in sorted((t, e["name"]) for e in entries for t in e["types"]):
        lines.append(f'    "{t}": "{name}",')
    lines += ["}", ""]
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv
    entries = load()
    outputs = {README: render_readme(entries), PY_OUT: render_python(entries)}
    stale = [p for p, content in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != content]
    if check:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)} (run python3 tools/sync_node_support.py)")
        sys.exit(1 if stale else 0)
    for p in stale:
        p.write_text(outputs[p], encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
